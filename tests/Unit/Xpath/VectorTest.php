declare(strict_types=1);

namespace EinvoiceValidator\Tests\Unit\Xpath;

use EinvoiceValidator\Devkit\Xpath\Parser\Parser;
use EinvoiceValidator\Xpath\Ast\AstSerializer;
use EinvoiceValidator\Xpath\Interpreter;
use PHPUnit\Framework\TestCase;
use Throwable;

/**
 * Runs the language-neutral test vectors under `tests/vectors/`.
 *
 * ⚠️ **THESE VECTORS EXIST FOR A SECOND IMPLEMENTATION, NOT FOR THIS ONE.** The JavaScript port has to
 * pass exactly the same expressions with exactly the same results; PHPUnit tests cannot be read from
 * JavaScript, so the expectations live in JSON and both sides load them.
 *
 * ⚠️ **AND THEY ARE DERIVED FROM THE EXISTING TESTS, NOT WRITTEN BESIDE THEM.** Every vector comes
 * from an assertion in `InterpreterTest`, `FunctionLibraryTest` or `ComparisonsTest`. Vectors made up
 * independently would let both sides agree on something neither of the original tests ever claimed -
 * and that would be called parity.
 *
 * ⚠️ **THE EXPECTATIONS WERE NOT RECORDED FROM A RUN.** They are the values the original assertions
 * name. A vector file generated by running the library would be green by construction and would prove
 * nothing about either implementation.
 */
final class VectorTest extends TestCase
{
    private const DIR = __DIR__ . '/../../vectors';

    /**
     * @return array<string, array{0: array<string, mixed>, 1: array<string, string>, 2: string, 3: string}>
     */
    public static function vectorProvider(): array
    {
        $out = [];

        foreach (glob(self::DIR . '/*.json') ?: [] as $file) {
            $data = json_decode((string) file_get_contents($file), true);

            self::assertIsArray($data, "not valid JSON: $file");

            $namespaces = $data['namespaces'] ?? [];

            foreach ($data['vectors'] as $vector) {
                $id = $data['id'] . '/' . $vector['id'];

                // ⚠️ The key is the vector id, so a failing case is named in the PHPUnit output. With
                // a numeric key the message says "data set #23", and the JSON has to be counted by
                // hand to find out which expression that was.
                $out[$id] = [$vector, $namespaces, basename($file), (string) $data['id']];
            }
        }

        self::assertNotSame([], $out, 'no vectors found - tests/vectors/ is empty?');

        return $out;
    }

    /**
     * @param array<string, mixed> $vector
     * @param array<string, string> $namespaces
     */
    #[\PHPUnit\Framework\Attributes\DataProvider('vectorProvider')]
    public function testVector(array $vector, array $namespaces, string $file, string $setId): void
    {
        $dom = new \DOMDocument();
        $dom->loadXML((string) $vector['xml']);

        $root = $dom->documentElement;
        self::assertNotNull($root, "document element missing in {$vector['id']}");

        $interpreter = new Interpreter($namespaces);

        $context = $root;

        /**
         * ⚠️ THE CONTEXT NODE IS SELECTED WITH THE SAME INTERPRETER THAT IS UNDER TEST - which is
         * circular, and deliberately so: the alternative is a second selection mechanism in the
         * vector format that the JavaScript side would also have to implement. The selectors used
         * are single child steps; a vector whose `contextPath` fails announces itself immediately,
         * because the assertion below it then has nothing to stand on.
         */
        if (isset($vector['contextPath'])) {
            $selected = $interpreter->evaluate(Parser::parse((string) $vector['contextPath']), $root)->first();

            self::assertInstanceOf(\DOMNode::class, $selected, "contextPath selected no node in {$vector['id']}");

            $context = $selected;
        }

        $expect = $vector['expect'];

        if (($expect['error'] ?? false) === true) {
            $threw = false;

            try {
                $interpreter->evaluate(Parser::parse((string) $vector['expr']), $context);
            } catch (Throwable $e) {
                $threw = true;
            }

            self::assertTrue($threw, "expected an error from {$vector['expr']}");

            return;
        }

        $result = $interpreter->evaluate(Parser::parse((string) $vector['expr']), $context);

        $where = $vector['id'] . ' ( ' . $file . ' ): ' . $vector['expr'];

        if (array_key_exists('empty', $expect)) {
            self::assertSame($expect['empty'], $result->isEmpty(), "$where - isEmpty");
        }

        if (array_key_exists('count', $expect)) {
            self::assertSame($expect['count'], $result->count(), "$where - count");
        }

        if (array_key_exists('ebv', $expect)) {
            self::assertSame($expect['ebv'], $result->effectiveBooleanValue(), "$where - effective boolean value");
        }

        if (array_key_exists('string', $expect)) {
            $first = $result->first();
            self::assertNotNull($first, "$where - expected a value, got the empty sequence");
            self::assertSame($expect['string'], $first->asString(), "$where - string value");
        }

        if (array_key_exists('boolean', $expect)) {
            $first = $result->first();
            self::assertNotNull($first, "$where - expected a value, got the empty sequence");
            self::assertSame($expect['boolean'], $first->asBoolean(), "$where - boolean value");
        }

        if (array_key_exists('text', $expect)) {
            $first = $result->first();
            self::assertInstanceOf(\DOMNode::class, $first, "$where - expected a node");
            self::assertSame($expect['text'], $first->textContent, "$where - text content");
        }

        if (array_key_exists('strings', $expect)) {
            $actual = array_map(static fn ($v) => $v->asString(), $result->items());
            self::assertSame($expect['strings'], $actual, "$where - sequence of strings");
        }
    }

    /**
     * The stored AST of every vector must be the one the parser produces.
     *
     * ⚠️ **THE JAVASCRIPT PORT WILL HAVE NO PARSER, AND MUST NOT NEED ONE.** `Parser` lives in
     * `devkit/`, outside the shipped runtime, because the rule packages under `rulesets/` already
     * carry compiled ASTs - the runtime interprets trees, not text. So the vectors carry their tree
     * as well ( `tests/vectors/ast/`, generated by `devkit/Cli/vector-ast.php` ), and this test is
     * what keeps that copy honest.
     *
     * ⚠️ AND IT COMPARES THE **OBJECTS**, NOT THE JSON. Two different serialisations of the same tree
     * are the same tree; a string comparison would fail on key order and on a `pos` that shifted by
     * one, and would say nothing about whether the JS side can evaluate it.
     *
     * @param array<string, mixed> $vector
     * @param array<string, string> $namespaces
     */
    #[\PHPUnit\Framework\Attributes\DataProvider('vectorProvider')]
    public function testStoredAstMatchesTheParser(array $vector, array $namespaces, string $file, string $setId): void
    {
        $astFile = self::DIR . '/ast/' . $setId . '.ast.json';

        self::assertFileExists($astFile, 'run `php devkit/Cli/vector-ast.php --apply`');

        $asts = json_decode((string) file_get_contents($astFile), true);

        self::assertArrayHasKey(
            $vector['id'],
            $asts['asts'],
            "no stored AST for {$vector['id']} - run `php devkit/Cli/vector-ast.php --apply`"
        );

        $stored = $asts['asts'][$vector['id']];

        // A vector whose expression does not even parse is recorded as such; there is nothing to
        // compare then, and the interpreter test above already asserts that it fails.
        if (isset($stored['parseError'])) {
            self::assertTrue(
                ($vector['expect']['error'] ?? false) === true,
                "{$vector['id']} does not parse but is not marked as an error case"
            );

            return;
        }

        $restored = AstSerializer::fromJson((string) json_encode(['astVersion' => 1, 'root' => $stored]));

        self::assertEquals(
            Parser::parse((string) $vector['expr']),
            $restored,
            "stored AST differs from the parser for {$vector['id']}: {$vector['expr']}"
        );
    }
}
