<?php

/**
 * Compiles every test vector's expression into its AST and writes it next to the vectors.
 *
 *   php devkit/Cli/vector-ast.php            reports differences, writes nothing
 *   php devkit/Cli/vector-ast.php --apply    writes tests/vectors/ast/<id>.ast.json
 *
 * ⚠️ **THE JAVASCRIPT SIDE WILL HAVE NO PARSER, AND IT DOES NOT NEED ONE.** `Parser` lives in
 * `devkit/`, not in the runtime: the rule packages under `rulesets/` already carry compiled ASTs, and
 * the runtime interprets those. A port that started with the parser would rebuild the one part that
 * is deliberately not shipped. So the vectors have to carry their AST too - otherwise the JS side
 * cannot run a single one of them.
 *
 * ⚠️ **THE AST IS DERIVED, THE EXPECTATIONS ARE NOT.** This tool generates only the translation of an
 * expression into a tree; `expect` stays hand-written in the vector files, taken from the original
 * assertions. Generating expectations would make both implementations agree with a recording instead
 * of with the specification.
 *
 * ⚠️ **AND IT WRITES INTO A SEPARATE FILE, NOT INTO THE VECTORS.** The vector files are maintained by
 * hand; a tool that rewrites them would reformat every line and bury the next real change in noise.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */

declare(strict_types=1);

require __DIR__ . '/../../vendor/autoload.php';

use EinvoiceValidator\Devkit\Xpath\Parser\Parser;
use EinvoiceValidator\Xpath\Ast\AstSerializer;

/**
 * ⚠️ `$argv` IS NOT GUARANTEED TO EXIST - it appears only when `register_argc_argv` is on, which is
 * the default for the CLI SAPI and NOT for every configuration. Reading it out of `$_SERVER` and
 * mapping to strings gives the same list with a type static analysis can follow, without a cast that
 * only silences the message.
 */
$arguments = array_map('strval', (array) ($_SERVER['argv'] ?? []));

$apply = in_array('--apply', $arguments, true);

$vectorDir = __DIR__ . '/../../tests/vectors';
$astDir    = $vectorDir . '/ast';

$files = glob($vectorDir . '/*.json') ?: [];

if ($files === []) {
    fwrite(STDERR, "keine Vektordateien unter $vectorDir\n");
    exit(1);
}

$abweichend = 0;

foreach ($files as $file) {
    $data = json_decode((string) file_get_contents($file), true);

    if (!is_array($data) || !isset($data['vectors'])) {
        fwrite(STDERR, 'keine Vektoren in ' . basename($file) . "\n");
        exit(1);
    }

    $out = [
        'astVersion' => 1,
        'id' => $data['id'],
        'source' => basename($file),
        '_comment' => 'GENERATED by devkit/Cli/vector-ast.php - do not edit. The expressions live in '
            . basename($file),
        'asts' => [],
    ];

    $fehler = [];

    foreach ($data['vectors'] as $vector) {
        $expr = (string) $vector['expr'];

        try {
            // ⚠️ `toJson()` returns a complete document with its own `astVersion`; only the tree
            // itself belongs in the map, so that the file has ONE version statement and not one per
            // vector.
            $tree = json_decode(AstSerializer::toJson(Parser::parse($expr)), true);

            $out['asts'][$vector['id']] = $tree['root'];
        } catch (Throwable $e) {
            /**
             * ⚠️ A VECTOR THAT DOES NOT EVEN PARSE IS STILL A VECTOR - the error cases
             * ( `unknownprefix:Foo`, `no-such-function('x')` ) are supposed to fail, and some of them
             * fail in the parser rather than in the interpreter. Recording that is more useful than
             * skipping them: the JS side has to fail on them too.
             */
            $out['asts'][$vector['id']] = ['parseError' => $e->getMessage()];

            $fehler[] = $vector['id'];
        }
    }

    $ziel = $astDir . '/' . $data['id'] . '.ast.json';
    $neu  = json_encode($out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";
    $alt  = is_file($ziel) ? (string) file_get_contents($ziel) : null;

    $gleich = $alt === $neu;

    printf(
        "  %-24s %3d Ausdrücke, %d im Parser gescheitert   %s\n",
        basename($file),
        count($data['vectors']),
        count($fehler),
        $gleich ? '=' : ($alt === null ? '+ neu' : '~ geändert')
    );

    if ($gleich) {
        continue;
    }

    $abweichend++;

    if (!$apply) {
        continue;
    }

    if (!is_dir($astDir)) {
        mkdir($astDir, 0777, true);
    }

    file_put_contents($ziel, $neu);
}

echo ($apply ? 'Geschrieben' : 'Trockenlauf') . ": $abweichend Datei(en) abweichend.\n";

// ⚠️ In the dry run a difference is an error - that way the call serves as a CI check
// ( "generate and diff" ) without a second switch.
exit(!$apply && $abweichend > 0 ? 1 : 0);
